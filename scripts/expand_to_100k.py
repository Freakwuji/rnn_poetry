def gen_variants(poem, n=2):
    """对一首诗生成 n 个变体"""
    if ':' not in poem:
        return []
    title, content = poem.split(':', 1)
    variants = []
    chars = list(content)
    sub_map = {'春':['春','芳','韶'], '秋':['秋','霜','寒'], '风':['风','云','烟'],
               '月':['月','露','霜'], '花':['花','蕊','萼'], '山':['山','峰','峦'],
               '水':['水','川','江'], '人':['人','客','翁'], '归':['归','还','回'],
               '落':['落','坠','飘'], '明':['明','清','皎'], '白':['白','素','皓']}
    for vi in range(n):
        new_chars = chars.copy()
        for i, c in enumerate(new_chars):
            if c in sub_map and random.random() < 0.15:
                new_chars[i] = random.choice(sub_map[c])
        new_content = ''.join(new_chars)
        if new_content != content:
            variants.append(f'{title}变{vi+1}:{new_content}')
    return variants

